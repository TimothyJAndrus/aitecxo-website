import { Stack, StackProps, CfnOutput, Duration, Fn } from 'aws-cdk-lib';
import { Construct } from 'constructs';
import * as route53 from 'aws-cdk-lib/aws-route53';

export interface DnsStackProps extends StackProps {
  domainName: string;
}

/**
 * Owns the public hosted zone only. Deploy this first, delegate the domain's
 * nameservers (at the registrar) to the output values, then deploy the site stack so
 * ACM DNS validation can succeed.
 */
export class DnsStack extends Stack {
  public readonly hostedZone: route53.PublicHostedZone;

  constructor(scope: Construct, id: string, props: DnsStackProps) {
    super(scope, id, props);

    this.hostedZone = new route53.PublicHostedZone(this, 'HostedZone', {
      zoneName: props.domainName,
    });

    // --- Email (Google Workspace) ---
    // Delegating the domain to Route 53 makes this zone authoritative for ALL
    // records, so the mail records that lived at the previous DNS host must be
    // recreated here or email stops flowing. These mirror the prior setup.
    new route53.MxRecord(this, 'GoogleWorkspaceMx', {
      zone: this.hostedZone,
      values: [{ priority: 1, hostName: 'smtp.google.com' }],
      ttl: Duration.hours(1),
    });

    // Apex TXT set: Google domain verification + SPF (authorizes Google to send
    // mail for this domain). Both strings live in one TXT record set at the apex;
    // there must be exactly one v=spf1 record.
    new route53.TxtRecord(this, 'GoogleSiteVerification', {
      zone: this.hostedZone,
      values: [
        'google-site-verification=gYaeJ96KHaynMkFjxQ1n4BkWiua-1BIiG2qE0mKT8hg',
        'v=spf1 include:_spf.google.com ~all',
      ],
      ttl: Duration.hours(1),
    });

    // DMARC — DKIM + SPF verified passing end-to-end, so enforce at quarantine.
    // Ramp to p=reject after a monitoring period with clean aggregate (rua) reports.
    new route53.TxtRecord(this, 'Dmarc', {
      zone: this.hostedZone,
      recordName: '_dmarc',
      values: ['v=DMARC1; p=quarantine; rua=mailto:dmarc@aitecxo.com'],
      ttl: Duration.hours(1),
    });

    // DKIM public key generated by Google Workspace (selector "google").
    // CDK splits this >255-char value into 255-char chunks within a single TXT
    // record, which resolvers reassemble.
    new route53.TxtRecord(this, 'GoogleDkim', {
      zone: this.hostedZone,
      recordName: 'google._domainkey',
      values: [
        'v=DKIM1; k=rsa; p=MIIBIjANBgkqhkiG9w0BAQEFAAOCAQ8AMIIBCgKCAQEAwhnPaUYDQiJDI79Be/nqPjtSIjQdAolBzYXIQtF09YwCWd2rxcy3rvB8f//0Jkc2D4+Yg3RwsfSTs1cF7/XGeIFVVrfomVMBU4+d6ALfj5PvDFP1rGEeEyMYKSnxVRkULS21Fl1TbwOEXJVd0yDP5opPNSJ/VhjcmMErvUm/pK3Do86N8vzWIGqJgwuojzcVwjrVq/VUlu0cWT+/giyU7fFWIdr42rTBQ+nIcEnNy0U+LLZz8m5d4QERnzkg6Ak+8FE/LIDc1tU72TkpfHzQRr1IB6HqaeW+/wEmc0nBpcT1HbzlE4p+KMmisUPcRlS9UqxlsfpSHE+HQQEDoUr0wwIDAQAB',
      ],
      ttl: Duration.hours(1),
    });

    new CfnOutput(this, 'HostedZoneId', { value: this.hostedZone.hostedZoneId });
    new CfnOutput(this, 'HostedZoneNameServers', {
      description: "Point the domain's nameservers (at Google) to these values.",
      value: Fn.join(', ', this.hostedZone.hostedZoneNameServers ?? []),
    });
  }
}
